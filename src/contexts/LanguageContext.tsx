// BUG-03：导出给 src/contexts/LanguageContext.test.ts 做静态一致性校验用——
// 不影响运行时行为，只是让"扫描代码里所有 t("key") 调用，比对字典里是否存在"
// 这类测试不需要真的挂载 LanguageProvider 就能跑。
export const translations: Record<Language, Record<string, string>> = {
  zh, en, ar, ja, ko, fr, es, de, ru, pt,
};

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() =>
    (localStorage.getItem("los-lang") as Language) || "zh"
  );

  const setLang = useCallback((l: Language) => {
    setLangState(l);
    localStorage.setItem("los-lang", l);
    document.documentElement.dir = l === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = l;
  }, []);

  const t = useCallback((key: string, params?: Record<string, string | number>): string => {
    let text = translations[lang]?.[key] || translations.en?.[key] || translations.zh?.[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, String(v));
      });
    }
    return text;
  }, [lang]);

  const dir = lang === "ar" ? "rtl" : "ltr";

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, dir }}>
      {children}
    </LanguageContext.Provider>
  );
}

// eslint-disable-next-line react-refresh/only-export-components
export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
}
